#!/usr/bin/env python3
"""Generate the minimal EMG-BIDS example dataset in examples/bids_minimal/.

The dataset contains one subject with a short synthetic HD-sEMG recording
(EDF+, 8 monopolar channels, 1000 Hz, 10 s) from a 2 × 4 electrode grid on the
right vastus lateralis. Electrode positions are given in the device-internal
child coordinate system ``gridVL`` (mm), which is anchored to the UNISEP right
thigh coordinate system ``thigh`` (percent) via the coordinate-system files of
examples/emg_bids/ (copied byte-for-byte, renamed to BIDS file names).

Requires: numpy, pyedflib.
Usage:    python scripts/make_bids_minimal.py
Validate: bids-validator-deno examples/bids_minimal
"""
from __future__ import annotations

import json
import shutil
from datetime import datetime
from pathlib import Path

import numpy as np
import pyedflib

REPO = Path(__file__).resolve().parents[1]
OUT = REPO / "examples" / "bids_minimal"
SRC = REPO / "examples" / "emg_bids"

SFREQ = 1000  # Hz
DURATION = 10  # s
N_ROWS, N_COLS, PITCH_MM = 2, 4, 8
TASK = "demo"


def write_json(path: Path, obj: dict) -> None:
    path.write_text(json.dumps(obj, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")


def write_tsv(path: Path, header: list[str], rows: list[list]) -> None:
    lines = ["\t".join(header)] + ["\t".join(str(v) for v in r) for r in rows]
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def electrodes() -> list[tuple[str, float, float]]:
    """Grid electrodes E1..E8: origin at E1, x along rows, y along columns (mm)."""
    out = []
    for row in range(N_ROWS):
        for col in range(N_COLS):
            out.append((f"E{row * N_COLS + col + 1}", col * PITCH_MM, row * PITCH_MM))
    return out


def synthetic_emg(n_channels: int) -> np.ndarray:
    """Gaussian noise modulated by three 2-s 'contractions' (µV)."""
    rng = np.random.default_rng(42)
    t = np.arange(SFREQ * DURATION) / SFREQ
    envelope = 5 + 95 * sum(np.exp(-((t - c) ** 2) / (2 * 0.4**2)) for c in (2, 5, 8))
    data = rng.normal(size=(n_channels, t.size)) * envelope
    gains = np.linspace(0.6, 1.0, n_channels)[:, None]
    return data * gains


def main() -> int:
    if OUT.exists():
        shutil.rmtree(OUT)
    emg_dir = OUT / "sub-01" / "emg"
    emg_dir.mkdir(parents=True)

    write_json(OUT / "dataset_description.json", {
        "Name": "UNISEP minimal EMG-BIDS example",
        "BIDSVersion": "1.11.1",
        "DatasetType": "raw",
        "License": "CC0",
        "Authors": ["UNISEP contributors"],
        "GeneratedBy": [{
            "Name": "make_bids_minimal.py",
            "Description": "Synthetic data generated by scripts/make_bids_minimal.py",
            "CodeURL": "https://github.com/unisep-framework/unisep-framework.github.io",
        }],
    })
    (OUT / "README").write_text(
        "UNISEP minimal EMG-BIDS example\n"
        "================================\n\n"
        "Synthetic data. One subject, one 10-s recording from a 2 x 4 HD-sEMG grid on the\n"
        "right vastus lateralis (8 monopolar channels, 1000 Hz, EDF+).\n\n"
        "Electrode positions are given in the device-internal child coordinate system\n"
        "'gridVL' (mm). It is anchored to the UNISEP right-thigh coordinate system 'thigh'\n"
        "(percent) through ParentCoordinateSystem, AnchorElectrode and AnchorCoordinates.\n"
        "MeasurementMethod and PrecisionLevel in the gridVL coordinate-system file are\n"
        "UNISEP extension keys, not BIDS keys.\n\n"
        "Generated by scripts/make_bids_minimal.py; see https://unisep-framework.github.io\n",
        encoding="utf-8")
    write_tsv(OUT / "participants.tsv", ["participant_id"], [["sub-01"]])

    elec = electrodes()
    names = [e[0] for e in elec]
    data = synthetic_emg(len(names))

    edf_path = emg_dir / f"sub-01_task-{TASK}_emg.edf"
    with pyedflib.EdfWriter(str(edf_path), len(names), file_type=pyedflib.FILETYPE_EDFPLUS) as w:
        w.setStartdatetime(datetime(2026, 1, 1, 12, 0, 0))
        w.setSignalHeaders([{
            "label": n, "dimension": "uV", "sample_frequency": SFREQ,
            "physical_max": 1000.0, "physical_min": -1000.0,
            "digital_max": 32767, "digital_min": -32768,
            "transducer": "Ag/AgCl surface electrode", "prefilter": "HP:10Hz LP:500Hz",
        } for n in names])
        w.writeSamples(list(np.clip(data, -1000, 1000)))

    write_json(emg_dir / f"sub-01_task-{TASK}_emg.json", {
        "TaskName": TASK,
        "TaskDescription": "Three brief isometric knee-extension contractions (synthetic).",
        "EMGPlacementScheme": "Measured",
        "EMGReference": "Monopolar; reference electrode on the right patella",
        "SamplingFrequency": SFREQ,
        "PowerLineFrequency": 50,
        "RecordingType": "continuous",
        "SoftwareFilters": "n/a",
        "HardwareFilters": {"Bandpass": {"Low cutoff (Hz)": 10, "High cutoff (Hz)": 500}},
        "EMGChannelCount": len(names),
        "RecordingDuration": DURATION,
        "Manufacturer": "n/a (synthetic data)",
        "InterelectrodeDistance": PITCH_MM,
    })
    write_tsv(emg_dir / f"sub-01_task-{TASK}_channels.tsv",
              ["name", "type", "units", "signal_electrode", "reference", "group", "target_muscle"],
              [[n, "EMG", "uV", n, "REF", "gridVL", "vastus lateralis"] for n in names])
    write_tsv(emg_dir / "sub-01_electrodes.tsv",
              ["name", "x", "y", "z", "coordinate_system", "type", "group"],
              [[n, x, y, "n/a", "gridVL", "surface", "gridVL"] for n, x, y in elec])

    shutil.copyfile(SRC / "space-thigh_coordsystem.json", emg_dir / "sub-01_space-thigh_coordsystem.json")
    shutil.copyfile(SRC / "space-gridVL_coordsystem.json", emg_dir / "sub-01_space-gridVL_coordsystem.json")

    print(f"wrote {sum(1 for p in OUT.rglob('*') if p.is_file())} files to {OUT.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
